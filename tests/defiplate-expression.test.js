"use strict";
const assert = require("node:assert/strict");
const { createGame } = require("./simulation-harness");
const game = createGame();
game.rb.setup({ characterKeys: ["defiplate", "needle"], seed: 42 });
const ctx = game.elements.get("game").getContext("2d");
let ellipses = [], rectangles = 0;
ctx.ellipse = (...args) => ellipses.push(args);
ctx.fillRect = () => rectangles++;
game.debug.drawFace(0);
assert.equal(ellipses.length, 3, "logo must have two slots and a center hole");
assert.equal(rectangles, 0, "must not draw a face panel");
const idleHeight = ellipses[0][3];
game.debug.fighters[0].chargingPunch = true;
ellipses = [];
game.debug.drawFace(0);
assert.equal(ellipses.length, 3);
assert(ellipses[0][3] < idleHeight, "charging must narrow the handle slots");
game.debug.drawFace(1);
assert(rectangles > 0, "other fighters retain their faces");
console.log("DefiPlate expressions: logo holes only, responsive charge expression, other faces preserved.");
