"use strict";
const assert = require("node:assert/strict");
const { createGame } = require("./simulation-harness");
const game = createGame();
game.rb.setup({characterKeys:["orbit","anchor"],seed:1});
const orbit = game.debug.fighters[0];
orbit.onGround = true;
orbit.face = {x:1,y:0};
assert.equal(game.debug.getAssetAnimation(0).flip,false);
orbit.face = {x:-1,y:0};
assert.equal(game.debug.getAssetAnimation(0).flip,true);
game.debug.advancePlatforms(0.1);
assert.equal(game.debug.getAssetAnimation(0).frame,1,"idle should run at authored 10 fps");
orbit.onGround = false;
for (const [speed,min,max] of [[-400,1,12],[0,13,14],[400,15,25]]) {
  orbit.vy = speed;
  const animation=game.debug.getAssetAnimation(0);
  assert.equal(animation.clip,"jump");
  assert(animation.frame>=min && animation.frame<=max,`wrong airborne phase for ${speed}`);
}
orbit.dashCarryTimer = 0.3;
orbit.vx = 900;
const dash=game.debug.getAssetAnimation(0);
assert.equal(dash.clip,"dash","PRO air dash should use its dedicated authored dash");
assert.equal(dash.dash,true);
assert(dash.frame>=0 && dash.frame<5);
orbit.onGround = true;
orbit.attack={age:0.1,startup:0.075,active:0.13,total:0.5,charge:0,dir:{x:1,y:0}};
assert([3,4].includes(game.debug.getAssetAnimation(0).frame),"visual strike must align with active hitbox");
orbit.attack=null;
orbit.hitstun=1;
game.debug.drawFace(0);
game.debug.advancePlatforms(0.045);
assert.equal(game.debug.getAssetAnimation(0).frame,1,"hurt should use authored frame durations");
orbit.health=0;
game.debug.drawFace(0);
game.debug.advancePlatforms(4);
assert.equal(game.debug.getAssetAnimation(0).frame,19,"death must hold its last frame");
game.rb.setup({characterKeys:["needle","anchor"]});
game.debug.fighters[0].face={x:1,y:0};
assert.equal(game.debug.getAssetAnimation(0).flip,false,"missing facing metadata must default to right-facing");
console.log(JSON.stringify({tests:"passed",orbitFacing:true,airPhases:true,attackTiming:true,authoredTiming:true}));
